begin;

create table if not exists public.progress_contract_items_dedupe_backup (
  backup_id bigint generated by default as identity primary key,
  archived_at timestamptz not null default now(),
  reason text not null,
  contract_item_id text not null,
  contract_version_id text,
  project_name text,
  source_key text,
  row_data jsonb not null
);

drop table if exists pg_temp.cm_semantic_duplicate_map_v524854483;

create temporary table pg_temp.cm_semantic_duplicate_map_v524854483
on commit drop
as
with target_rows as (
  select
    pci.*,
    concat_ws(
      '||',
      lower(regexp_replace(btrim(coalesce(nullif(pci.classification, ''), nullif(pci.housing_type, ''), '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(pci.option_type, '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(nullif(pci.base_item_name, ''), nullif(pci.item_name, ''), '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(pci.specification, '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(pci.unit, '')), '\s+', '', 'g')),
      coalesce(pci.contract_quantity, 0)::text,
      coalesce(pci.contract_material_amount, 0)::text,
      coalesce(pci.contract_labor_amount, 0)::text,
      coalesce(pci.contract_expense_amount, 0)::text
    ) as semantic_key
  from public.progress_contract_items pci
  where pci.contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'::uuid
),
new_contract_rows as (
  select *
  from target_rows
  where source_key like 'new-contract:%'
),
semantic_occurrence_rows as (
  select *
  from target_rows
  where source_key ~ '\|.*#[0-9]+$'
)
select
  legacy.id as duplicate_id,
  current_row.id as keep_id,
  current_row.contract_version_id,
  current_row.project_name,
  current_row.semantic_key,
  legacy.source_key as duplicate_source_key,
  current_row.source_key as keep_source_key
from semantic_occurrence_rows legacy
join new_contract_rows current_row
  on current_row.semantic_key = legacy.semantic_key;

do $validate_semantic_cleanup$
declare
  v_target_count integer;
  v_new_contract_count integer;
  v_semantic_occurrence_count integer;
  v_map_count integer;
  v_distinct_keep_count integer;
  v_distinct_duplicate_count integer;
  v_claim_item_count integer;
begin
  select count(*)
    into v_target_count
  from public.progress_contract_items
  where contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'::uuid;

  select count(*)
    into v_new_contract_count
  from public.progress_contract_items
  where contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'::uuid
    and source_key like 'new-contract:%';

  select count(*)
    into v_semantic_occurrence_count
  from public.progress_contract_items
  where contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'::uuid
    and source_key ~ '\|.*#[0-9]+$';

  select
    count(*),
    count(distinct keep_id),
    count(distinct duplicate_id)
  into
    v_map_count,
    v_distinct_keep_count,
    v_distinct_duplicate_count
  from pg_temp.cm_semantic_duplicate_map_v524854483;

  select coalesce(max(item_count), 0)
    into v_claim_item_count
  from public.progress_claims
  where contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'::uuid;

  if v_target_count <> 182
     or v_new_contract_count <> 91
     or v_semantic_occurrence_count <> 91
     or v_map_count <> 91
     or v_distinct_keep_count <> 91
     or v_distinct_duplicate_count <> 91
     or v_claim_item_count <> 91
  then
    raise exception
      '안전검증 실패: 전체 %, new-contract %, 기존키 %, 연결쌍 %, keep %, duplicate %, 기성품목 %. 데이터가 진단 당시와 달라 정리를 중단합니다.',
      v_target_count,
      v_new_contract_count,
      v_semantic_occurrence_count,
      v_map_count,
      v_distinct_keep_count,
      v_distinct_duplicate_count,
      v_claim_item_count;
  end if;
end;
$validate_semantic_cleanup$;

insert into public.progress_contract_items_dedupe_backup (
  reason,
  contract_item_id,
  contract_version_id,
  project_name,
  source_key,
  row_data
)
select
  'v52.48.5.44.8.3 semantic duplicate: preserve new-contract key',
  pci.id::text,
  pci.contract_version_id::text,
  pci.project_name,
  pci.source_key,
  to_jsonb(pci)
from public.progress_contract_items pci
join pg_temp.cm_semantic_duplicate_map_v524854483 dm
  on dm.duplicate_id = pci.id;

drop table if exists pg_temp.cm_semantic_merged_mapping_v524854483;

create temporary table pg_temp.cm_semantic_merged_mapping_v524854483
on commit drop
as
with pair_rows as (
  select
    dm.keep_id,
    pci.process_type,
    pci.mapped_by_name,
    pci.mapped_at
  from pg_temp.cm_semantic_duplicate_map_v524854483 dm
  join public.progress_contract_items pci
    on pci.id in (dm.keep_id, dm.duplicate_id)
),
tokens as (
  select
    pr.keep_id,
    btrim(token) as token
  from pair_rows pr
  cross join lateral regexp_split_to_table(
    coalesce(pr.process_type, ''),
    '\s*\+\s*|\s*,\s*'
  ) token
  where btrim(token) <> ''
),
merged_process as (
  select
    keep_id,
    string_agg(distinct token, ' + ' order by token) as process_type
  from tokens
  group by keep_id
),
latest_mapping as (
  select distinct on (keep_id)
    keep_id,
    mapped_by_name,
    mapped_at
  from pair_rows
  where mapped_at is not null
     or btrim(coalesce(mapped_by_name, '')) <> ''
  order by keep_id, mapped_at desc nulls last
)
select
  dm.keep_id,
  mp.process_type,
  lm.mapped_by_name,
  lm.mapped_at
from pg_temp.cm_semantic_duplicate_map_v524854483 dm
left join merged_process mp
  on mp.keep_id = dm.keep_id
left join latest_mapping lm
  on lm.keep_id = dm.keep_id
group by
  dm.keep_id,
  mp.process_type,
  lm.mapped_by_name,
  lm.mapped_at;

update public.progress_contract_items pci
set
  process_type = coalesce(nullif(mm.process_type, ''), pci.process_type),
  mapped_by_name = coalesce(nullif(mm.mapped_by_name, ''), pci.mapped_by_name),
  mapped_at = coalesce(mm.mapped_at, pci.mapped_at)
from pg_temp.cm_semantic_merged_mapping_v524854483 mm
where pci.id = mm.keep_id;

do $fk_repoint$
declare
  v_fk record;
begin
  for v_fk in
    select
      child_ns.nspname as schema_name,
      child.relname as table_name,
      child_col.attname as column_name
    from pg_constraint fk
    join pg_class parent
      on parent.oid = fk.confrelid
    join pg_namespace parent_ns
      on parent_ns.oid = parent.relnamespace
    join pg_class child
      on child.oid = fk.conrelid
    join pg_namespace child_ns
      on child_ns.oid = child.relnamespace
    join pg_attribute child_col
      on child_col.attrelid = fk.conrelid
     and child_col.attnum = fk.conkey[1]
    join pg_attribute parent_col
      on parent_col.attrelid = fk.confrelid
     and parent_col.attnum = fk.confkey[1]
    where fk.contype = 'f'
      and parent_ns.nspname = 'public'
      and parent.relname = 'progress_contract_items'
      and parent_col.attname = 'id'
      and array_length(fk.conkey, 1) = 1
      and array_length(fk.confkey, 1) = 1
  loop
    execute format(
      'update %I.%I child
          set %I = dm.keep_id
         from pg_temp.cm_semantic_duplicate_map_v524854483 dm
        where child.%I::text = dm.duplicate_id::text',
      v_fk.schema_name,
      v_fk.table_name,
      v_fk.column_name,
      v_fk.column_name
    );
  end loop;
end;
$fk_repoint$;

delete from public.progress_contract_items pci
using pg_temp.cm_semantic_duplicate_map_v524854483 dm
where pci.id = dm.duplicate_id;

