-- 최종 결과: contract_item_count=91, distinct_source_key_count=91,
-- semantic_item_count=91, remaining_semantic_duplicate_rows=0이어야 정상입니다.
with target as (
  select
    pci.*,
    concat_ws(
      '||',
      lower(regexp_replace(btrim(coalesce(nullif(pci.classification, ''), nullif(pci.housing_type, ''), '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(pci.option_type, '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(nullif(pci.base_item_name, ''), nullif(pci.item_name, ''), '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(pci.specification, '')), '\s+', '', 'g')),
      lower(regexp_replace(btrim(coalesce(pci.unit, '')), '\s+', '', 'g')),
      coalesce(pci.contract_quantity, 0)::text,
      coalesce(pci.contract_material_amount, 0)::text,
      coalesce(pci.contract_labor_amount, 0)::text,
      coalesce(pci.contract_expense_amount, 0)::text
    ) as semantic_key
  from public.progress_contract_items pci
  where pci.contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'::uuid
),
semantic_groups as (
  select semantic_key, count(*) as group_count
  from target
  group by semantic_key
)
select
  count(*) as contract_item_count,
  count(distinct nullif(btrim(source_key), '')) as distinct_source_key_count,
  (select count(*) from semantic_groups) as semantic_item_count,
  (
    select coalesce(sum(group_count - 1), 0)
    from semantic_groups
    where group_count > 1
  ) as remaining_semantic_duplicate_rows,
  count(*) filter (where source_key like 'new-contract:%') as new_contract_item_count,
  count(*) filter (where btrim(coalesce(process_type, '')) <> '') as mapped_item_count,
  (
    select count(*)
    from public.progress_contract_items_dedupe_backup
    where reason = 'v52.48.5.44.8.3 semantic duplicate: preserve new-contract key'
      and contract_version_id = '48a16c0d-2908-4273-9ddc-1f1341ca839b'
  ) as backup_row_count
from target;
