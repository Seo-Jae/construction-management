-- 같은 현장/계약버전 재업로드 시 기존 계약품목을 현재 파일로 완전히 교체합니다.
-- exact source_key가 바뀌어도 동일 품목·규격·단위·순번의 기존 공정연결을 이어받습니다.
create or replace function public.sync_progress_contract_master_v1(
  p_project_name text,
  p_contract_version_label text,
  p_effective_date date,
  p_source_file_name text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project_name text := btrim(coalesce(p_project_name, ''));
  v_version_label text := btrim(coalesce(p_contract_version_label, ''));
  v_version_id uuid;
  v_item_count integer := 0;
  v_has_unit_price_columns boolean := false;
begin
  if auth.uid() is null then
    raise exception '로그인이 필요합니다.';
  end if;

  if v_project_name = '' then
    raise exception '현장명이 없습니다.';
  end if;

  if v_version_label = '' then
    raise exception '계약버전명이 없습니다.';
  end if;

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0
  then
    raise exception '동기화할 계약품목이 없습니다.';
  end if;

  perform pg_advisory_xact_lock(
    hashtext(
      'progress_contract_master:' ||
      v_project_name ||
      ':' ||
      v_version_label
    )
  );

  drop table if exists pg_temp.cm_contract_sync_items_v2;
  create temporary table pg_temp.cm_contract_sync_items_v2 (
    source_key text,
    source_row_no integer,
    sort_order integer,
    classification text,
    housing_type text,
    option_type text,
    work_zone text,
    item_name text,
    base_item_name text,
    specification text,
    unit text,
    process_type text,
    contract_quantity numeric,
    material_unit_price numeric,
    labor_unit_price numeric,
    expense_unit_price numeric,
    contract_material_amount numeric,
    contract_labor_amount numeric,
    contract_expense_amount numeric,
    identity_key text,
    identity_occurrence integer
  ) on commit drop;

  insert into pg_temp.cm_contract_sync_items_v2 (
    source_key,
    source_row_no,
    sort_order,
    classification,
    housing_type,
    option_type,
    work_zone,
    item_name,
    base_item_name,
    specification,
    unit,
    process_type,
    contract_quantity,
    material_unit_price,
    labor_unit_price,
    expense_unit_price,
    contract_material_amount,
    contract_labor_amount,
    contract_expense_amount
  )
  select
    btrim(coalesce(x.source_key, '')),
    x.source_row_no,
    x.sort_order,
    btrim(coalesce(x.classification, '')),
    btrim(coalesce(x.housing_type, x.classification, '')),
    btrim(coalesce(x.option_type, '기본')),
    btrim(coalesce(x.work_zone, '')),
    btrim(coalesce(x.item_name, '')),
    btrim(coalesce(x.base_item_name, x.item_name, '')),
    btrim(coalesce(x.specification, '')),
    btrim(coalesce(x.unit, '')),
    btrim(coalesce(x.process_type, '')),
    coalesce(x.contract_quantity, 0),
    coalesce(x.material_unit_price, 0),
    coalesce(x.labor_unit_price, 0),
    coalesce(x.expense_unit_price, 0),
    coalesce(x.contract_material_amount, coalesce(x.contract_quantity, 0) * coalesce(x.material_unit_price, 0)),
    coalesce(x.contract_labor_amount, coalesce(x.contract_quantity, 0) * coalesce(x.labor_unit_price, 0)),
    coalesce(x.contract_expense_amount, coalesce(x.contract_quantity, 0) * coalesce(x.expense_unit_price, 0))
  from jsonb_to_recordset(p_items) as x(
    source_key text,
    source_row_no integer,
    sort_order integer,
    classification text,
    housing_type text,
    option_type text,
    work_zone text,
    item_name text,
    base_item_name text,
    specification text,
    unit text,
    process_type text,
    contract_quantity numeric,
    material_unit_price numeric,
    labor_unit_price numeric,
    expense_unit_price numeric,
    contract_material_amount numeric,
    contract_labor_amount numeric,
    contract_expense_amount numeric
  );

  delete from pg_temp.cm_contract_sync_items_v2
  where source_key = ''
     or item_name = '';

  if exists (
    select 1
    from pg_temp.cm_contract_sync_items_v2
    group by source_key
    having count(*) > 1
  ) then
    raise exception '표준양식에 동일한 SYSTEM_ITEM_KEY가 중복되어 있습니다.';
  end if;

  update pg_temp.cm_contract_sync_items_v2
  set identity_key = concat_ws(
    '||',
    lower(regexp_replace(classification, '\s+', '', 'g')),
    lower(regexp_replace(option_type, '\s+', '', 'g')),
    lower(regexp_replace(base_item_name, '\s+', '', 'g')),
    lower(regexp_replace(specification, '\s+', '', 'g')),
    lower(regexp_replace(unit, '\s+', '', 'g'))
  );

  with ranked as (
    select
      ctid,
      row_number() over (
        partition by identity_key
        order by sort_order nulls last, source_row_no nulls last, source_key
      ) as occurrence
    from pg_temp.cm_contract_sync_items_v2
  )
  update pg_temp.cm_contract_sync_items_v2 target
  set identity_occurrence = ranked.occurrence
  from ranked
  where target.ctid = ranked.ctid;

  select count(*)
    into v_item_count
  from pg_temp.cm_contract_sync_items_v2;

  if v_item_count = 0 then
    raise exception '유효한 계약품목이 없습니다.';
  end if;

  select pcv.id
    into v_version_id
  from public.progress_contract_versions pcv
  where btrim(pcv.project_name) = v_project_name
    and btrim(pcv.version_label) = v_version_label
  order by pcv.created_at desc nulls last
  limit 1
  for update;

  if v_version_id is null then
    insert into public.progress_contract_versions (
      project_name,
      version_label,
      effective_date,
      source_file_name
    )
    values (
      v_project_name,
      v_version_label,
      p_effective_date,
      nullif(btrim(coalesce(p_source_file_name, '')), '')
    )
    returning id into v_version_id;
  else
    update public.progress_contract_versions
    set
      effective_date = coalesce(p_effective_date, effective_date),
      source_file_name = coalesce(
        nullif(btrim(coalesce(p_source_file_name, '')), ''),
        source_file_name
      )
    where id = v_version_id;
  end if;

  drop table if exists pg_temp.cm_contract_existing_mapping_v2;
  create temporary table pg_temp.cm_contract_existing_mapping_v2
  on commit drop
  as
  with existing_ranked as (
    select
      btrim(coalesce(pci.source_key, '')) as source_key,
      concat_ws(
        '||',
        lower(regexp_replace(btrim(coalesce(nullif(pci.classification, ''), nullif(pci.housing_type, ''), '')), '\s+', '', 'g')),
        lower(regexp_replace(btrim(coalesce(pci.option_type, '')), '\s+', '', 'g')),
        lower(regexp_replace(btrim(coalesce(nullif(pci.base_item_name, ''), nullif(pci.item_name, ''), '')), '\s+', '', 'g')),
        lower(regexp_replace(btrim(coalesce(pci.specification, '')), '\s+', '', 'g')),
        lower(regexp_replace(btrim(coalesce(pci.unit, '')), '\s+', '', 'g'))
      ) as identity_key,
      row_number() over (
        partition by concat_ws(
          '||',
          lower(regexp_replace(btrim(coalesce(nullif(pci.classification, ''), nullif(pci.housing_type, ''), '')), '\s+', '', 'g')),
          lower(regexp_replace(btrim(coalesce(pci.option_type, '')), '\s+', '', 'g')),
          lower(regexp_replace(btrim(coalesce(nullif(pci.base_item_name, ''), nullif(pci.item_name, ''), '')), '\s+', '', 'g')),
          lower(regexp_replace(btrim(coalesce(pci.specification, '')), '\s+', '', 'g')),
          lower(regexp_replace(btrim(coalesce(pci.unit, '')), '\s+', '', 'g'))
        )
        order by pci.sort_order nulls last, pci.source_row_no nulls last, pci.id::text
      ) as identity_occurrence,
      pci.process_type,
      pci.mapped_by_name,
      pci.mapped_at
    from public.progress_contract_items pci
    where pci.contract_version_id = v_version_id
  )
  select * from existing_ranked;

  delete from public.progress_contract_items
  where contract_version_id = v_version_id;

  select
    exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'progress_contract_items'
        and column_name = 'material_unit_price'
    )
    and exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'progress_contract_items'
        and column_name = 'labor_unit_price'
    )
    and exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'progress_contract_items'
        and column_name = 'expense_unit_price'
    )
  into v_has_unit_price_columns;

  if v_has_unit_price_columns then
    insert into public.progress_contract_items (
      contract_version_id,
      project_name,
      source_key,
      source_row_no,
      sort_order,
      classification,
      housing_type,
      option_type,
      work_zone,
      item_name,
      base_item_name,
      specification,
      unit,
      process_type,
      contract_quantity,
      material_unit_price,
      labor_unit_price,
      expense_unit_price,
      contract_material_amount,
      contract_labor_amount,
      contract_expense_amount,
      mapped_by_name,
      mapped_at
    )
    select
      v_version_id,
      v_project_name,
      s.source_key,
      s.source_row_no,
      s.sort_order,
      s.classification,
      case when s.classification <> '' then s.classification else s.housing_type end,
      s.option_type,
      s.work_zone,
      s.item_name,
      s.base_item_name,
      s.specification,
      s.unit,
      coalesce(nullif(me.process_type, ''), nullif(mf.process_type, ''), nullif(s.process_type, ''), ''),
      s.contract_quantity,
      s.material_unit_price,
      s.labor_unit_price,
      s.expense_unit_price,
      s.contract_material_amount,
      s.contract_labor_amount,
      s.contract_expense_amount,
      coalesce(nullif(me.mapped_by_name, ''), nullif(mf.mapped_by_name, '')),
      coalesce(me.mapped_at, mf.mapped_at)
    from pg_temp.cm_contract_sync_items_v2 s
    left join pg_temp.cm_contract_existing_mapping_v2 me
      on me.source_key = s.source_key
    left join pg_temp.cm_contract_existing_mapping_v2 mf
      on mf.identity_key = s.identity_key
     and mf.identity_occurrence = s.identity_occurrence
    order by s.sort_order, s.source_row_no;
  else
    insert into public.progress_contract_items (
      contract_version_id,
      project_name,
      source_key,
      source_row_no,
      sort_order,
      classification,
      housing_type,
      option_type,
      work_zone,
      item_name,
      base_item_name,
      specification,
      unit,
      process_type,
      contract_quantity,
      contract_material_amount,
      contract_labor_amount,
      contract_expense_amount,
      mapped_by_name,
      mapped_at
    )
    select
      v_version_id,
      v_project_name,
      s.source_key,
      s.source_row_no,
      s.sort_order,
      s.classification,
      case when s.classification <> '' then s.classification else s.housing_type end,
      s.option_type,
      s.work_zone,
      s.item_name,
      s.base_item_name,
      s.specification,
      s.unit,
      coalesce(nullif(me.process_type, ''), nullif(mf.process_type, ''), nullif(s.process_type, ''), ''),
      s.contract_quantity,
      s.contract_material_amount,
      s.contract_labor_amount,
      s.contract_expense_amount,
      coalesce(nullif(me.mapped_by_name, ''), nullif(mf.mapped_by_name, '')),
      coalesce(me.mapped_at, mf.mapped_at)
    from pg_temp.cm_contract_sync_items_v2 s
    left join pg_temp.cm_contract_existing_mapping_v2 me
      on me.source_key = s.source_key
    left join pg_temp.cm_contract_existing_mapping_v2 mf
      on mf.identity_key = s.identity_key
     and mf.identity_occurrence = s.identity_occurrence
    order by s.sort_order, s.source_row_no;
  end if;

  return jsonb_build_object(
    'project_name', v_project_name,
    'contract_version_id', v_version_id,
    'contract_version_label', v_version_label,
    'item_count', v_item_count,
    'process_mapping_preserved', true,
    'replace_mode', true,
    'semantic_mapping_fallback', true,
    'duplicate_guard', true,
    'sync_lock', true
  );
end;
$$;

revoke all on function public.sync_progress_contract_master_v1(
