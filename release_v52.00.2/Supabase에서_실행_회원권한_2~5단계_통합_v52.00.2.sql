create or replace function public.permission_phase2_is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_profiles up
    where up.auth_user_id = auth.uid()
      and coalesce(lower(trim(up.account_status)), 'active') = 'active'
      and lower(regexp_replace(coalesce(up.role, ''), '[[:space:]_-]+', '', 'g'))
        in ('최고관리자', 'superadmin', 'masteradmin')
  );
$$;

create or replace function public.admin_get_access_catalog_v2()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.permission_phase2_is_super_admin() then
    raise exception '최고관리자만 권한 기준정보를 조회할 수 있습니다.';
  end if;

  return jsonb_build_object(
    'departments', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'code', d.code,
        'name', d.name,
        'organization_type', d.organization_type,
        'sort_order', d.sort_order
      ) order by d.sort_order, d.name), '[]'::jsonb)
      from public.departments d
      where d.is_active = true
    ),
    'templates', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'code', t.code,
        'name', t.name,
        'organization_type', t.organization_type,
        'department_code', t.department_code,
        'description', t.description,
