create function public.admin_update_user_access_v2(
  p_user_id uuid,
  p_role text,
  p_position_title text,
  p_organization_type text,
  p_department_code text,
  p_permission_template_code text,
  p_access_scope text,
  p_project_names text[],
  p_project_access jsonb,
  p_permission_overrides jsonb,
  p_special_permissions jsonb,
  p_account_status text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_before jsonb;
  v_after jsonb;
  v_template public.permission_templates%rowtype;
  v_changed_fields jsonb;
  v_change_summary text;
begin
  if not public.permission_phase2_is_super_admin() then
    raise exception '최고관리자만 회원 권한설정을 변경할 수 있습니다.';
  end if;

  if p_organization_type not in ('본사', '현장', '외부업체') then
    raise exception '사용자 구분이 올바르지 않습니다.';
  end if;

  if p_access_scope not in ('home_project', 'selected', 'all') then
    raise exception '접근현장 범위가 올바르지 않습니다.';
  end if;

  if p_access_scope = 'all' and p_organization_type <> '본사' then
    raise exception '전체현장은 본사 사용자에게만 지정할 수 있습니다.';
  end if;

  if p_access_scope <> 'all' and coalesce(cardinality(p_project_names), 0) = 0 then
    raise exception '접근 현장을 하나 이상 지정해주세요.';
  end if;

  if p_access_scope = 'home_project' and coalesce(cardinality(p_project_names), 0) <> 1 then
    raise exception '소속현장 범위는 현장 한 곳만 지정해야 합니다.';
  end if;

  if not exists (
    select 1 from public.departments
    where code = p_department_code and is_active = true
  ) then
    raise exception '선택한 부서를 찾을 수 없습니다.';
  end if;

  select * into v_template
  from public.permission_templates
  where code = p_permission_template_code and is_active = true;

  if not found then
    raise exception '선택한 권한 템플릿을 찾을 수 없습니다.';
  end if;

  if v_template.organization_type not in ('공통', p_organization_type) then
    raise exception '사용자 구분과 권한 템플릿이 일치하지 않습니다.';
  end if;

  if v_template.department_code is not null
     and v_template.department_code <> p_department_code then
    raise exception '부서와 권한 템플릿이 일치하지 않습니다.';
  end if;

  if p_permission_template_code = 'super_admin'
     and p_role <> '최고관리자' then
    raise exception '최고관리자 템플릿은 최고관리자 역할에만 지정할 수 있습니다.';
  end if;

  if p_role = '최고관리자'
     and (
       p_permission_template_code <> 'super_admin'
       or p_organization_type <> '본사'
       or p_access_scope <> 'all'
     ) then
    raise exception '최고관리자는 본사·전체현장·최고관리자 템플릿으로 지정해야 합니다.';
  end if;

  if jsonb_typeof(coalesce(p_permission_overrides, '[]'::jsonb)) <> 'array' then
    raise exception '세부권한 형식이 올바르지 않습니다.';
  end if;

  if jsonb_typeof(coalesce(p_special_permissions, '[]'::jsonb)) <> 'array' then
    raise exception '특수권한 형식이 올바르지 않습니다.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_permission_overrides, '[]'::jsonb)) item
    left join public.permission_definitions pd
      on pd.permission_key = item->>'permission_key'
    where coalesce(item->>'effect', '') not in ('allow', 'deny')
       or trim(coalesce(item->>'scope_key', '')) = ''
       or pd.permission_key is null
       or pd.is_sensitive = true
       or (
         item->>'scope_key' <> '*'
         and (
           p_access_scope = 'all'
           or not ((item->>'scope_key') = any(coalesce(p_project_names, array[]::text[])))
         )
       )
  ) then
    raise exception '세부권한에 허용되지 않은 항목 또는 현장범위가 포함되어 있습니다.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements_text(coalesce(p_special_permissions, '[]'::jsonb)) as special_item(permission_value)
    left join public.permission_definitions pd
      on pd.permission_key = special_item.permission_value
    where pd.permission_key is null or pd.is_sensitive = false
  ) then
    raise exception '특수권한에 허용되지 않은 항목이 포함되어 있습니다.';
  end if;

  v_before := public.admin_user_access_snapshot_v2(p_user_id);

  update public.user_profiles
  set position_title = trim(coalesce(p_position_title, ''))
  where auth_user_id = p_user_id;

  if not found then
    raise exception '수정할 회원정보를 찾을 수 없습니다.';
  end if;

  perform public.admin_update_user_account_projects(
    p_user_id => p_user_id,
    p_role => p_role,
    p_organization_type => p_organization_type,
    p_project_names => case
      when p_access_scope = 'all' then array['전체현장']::text[]
      else p_project_names
    end,
    p_account_status => p_account_status
  );

  insert into public.user_access_settings_v2 (
    auth_user_id,
    organization_type,
    department_code,
    permission_template_code,
    access_scope,
    updated_at,
    updated_by
  ) values (
    p_user_id,
    p_organization_type,
    p_department_code,
    p_permission_template_code,
    p_access_scope,
    now(),
    auth.uid()
  )
  on conflict (auth_user_id) do update
  set organization_type = excluded.organization_type,
      department_code = excluded.department_code,
      permission_template_code = excluded.permission_template_code,
      access_scope = excluded.access_scope,
      updated_at = now(),
      updated_by = auth.uid();

  delete from public.user_project_access_v2
  where auth_user_id = p_user_id;

  if p_access_scope <> 'all' then
    insert into public.user_project_access_v2 (
      auth_user_id,
      project_name,
      access_start_date,
      access_end_date,
      is_active,
      updated_at
    )
    select distinct on (trim(item->>'project_name'))
      p_user_id,
      trim(item->>'project_name'),
      nullif(item->>'access_start_date', '')::date,
      nullif(item->>'access_end_date', '')::date,
      coalesce((item->>'is_active')::boolean, true),
      now()
    from jsonb_array_elements(coalesce(p_project_access, '[]'::jsonb)) item
    where trim(coalesce(item->>'project_name', '')) <> ''
      and trim(item->>'project_name') = any(p_project_names)
    order by trim(item->>'project_name');

    insert into public.user_project_access_v2 (
      auth_user_id,
      project_name,
      is_active,
      updated_at
    )
    select p_user_id, project_item.project_value, true, now()
    from unnest(p_project_names) as project_item(project_value)
    where trim(coalesce(project_item.project_value, '')) <> ''
      and not exists (
        select 1 from public.user_project_access_v2 current_access
        where current_access.auth_user_id = p_user_id
          and current_access.project_name = project_item.project_value
      );
  end if;

  delete from public.user_permission_overrides_v2
  where auth_user_id = p_user_id;

  if p_permission_template_code <> 'super_admin' then
    insert into public.user_permission_overrides_v2 (
      auth_user_id,
      scope_key,
      permission_key,
      effect,
      updated_at,
      updated_by
    )
    select distinct on (item->>'scope_key', item->>'permission_key')
      p_user_id,
      item->>'scope_key',
      item->>'permission_key',
      item->>'effect',
      now(),
      auth.uid()
    from jsonb_array_elements(coalesce(p_permission_overrides, '[]'::jsonb)) item
    order by item->>'scope_key', item->>'permission_key';
  end if;

  delete from public.user_special_permissions_v2
  where auth_user_id = p_user_id;

  if p_permission_template_code <> 'super_admin' then
    insert into public.user_special_permissions_v2 (
      auth_user_id,
      permission_key,
      updated_at,
      updated_by
    )
    select distinct p_user_id, special_item.permission_value, now(), auth.uid()
    from jsonb_array_elements_text(coalesce(p_special_permissions, '[]'::jsonb)) as special_item(permission_value);
  end if;

  v_after := public.admin_user_access_snapshot_v2(p_user_id);

  select coalesce(jsonb_agg(changed_key order by changed_key), '[]'::jsonb)
  into v_changed_fields
  from (
    select after_item.key as changed_key
    from jsonb_each(v_after) after_item
    where (v_before -> after_item.key) is distinct from after_item.value
  ) changed;

  v_change_summary := case
    when v_before #>> '{profile,account_status}' is distinct from p_account_status
      and p_account_status = 'active' then '계정 승인·사용 시작 및 권한 저장'
    when v_before #>> '{profile,account_status}' is distinct from p_account_status
      and p_account_status = 'disabled' then '계정 사용중지 및 권한 저장'
    when v_before #>> '{profile,account_status}' is distinct from p_account_status
      and p_account_status = 'rejected' then '가입 승인거절 및 권한 저장'
    else '회원 권한 설정 변경'
  end;

  if v_before is distinct from v_after then
    insert into public.user_access_audit_log_v2
      (target_user_id, changed_by, before_value, after_value, change_summary, changed_fields)
    values
      (p_user_id, auth.uid(), v_before, v_after, v_change_summary, v_changed_fields);
  end if;
end;
$$;

