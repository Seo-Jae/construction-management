create table if not exists public.permission_definitions (
  permission_key text primary key,
  area_code text not null,
  menu_code text not null,
  action_code text not null,
  action_label text not null,
  action_rank integer not null default 10,
  is_sensitive boolean not null default false,
  created_at timestamptz not null default now(),
  unique (menu_code, action_code)
);

create table if not exists public.permission_templates (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  organization_type text not null
    check (organization_type in ('공통', '본사', '현장', '외부업체')),
  department_code text references public.departments(code),
  description text not null default '',
  sort_order integer not null default 0,
  is_system boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.template_menu_levels (
  template_code text not null references public.permission_templates(code) on delete cascade,
  menu_code text not null,
  permission_level text not null
    check (permission_level in ('조회', '작성', '관리', '결재')),
  level_rank integer not null
    check (level_rank in (10, 25, 50, 70)),
  primary key (template_code, menu_code)
);

create table if not exists public.template_permissions (
  template_code text not null references public.permission_templates(code) on delete cascade,
  permission_key text not null references public.permission_definitions(permission_key) on delete cascade,
  is_granted boolean not null default true,
  primary key (template_code, permission_key)
);

create table if not exists public.user_access_settings_v2 (
  auth_user_id uuid primary key references auth.users(id) on delete cascade,
  organization_type text not null default '현장'
