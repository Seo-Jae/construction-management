  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.user_project_access_v2 (
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  project_name text not null,
  access_start_date date,
  access_end_date date,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (auth_user_id, project_name),
  check (access_end_date is null or access_start_date is null or access_end_date >= access_start_date)
);

create table if not exists public.user_access_audit_log_v2 (
  id bigint generated by default as identity primary key,
  target_user_id uuid not null references auth.users(id) on delete cascade,
  changed_by uuid references auth.users(id),
  before_value jsonb,
  after_value jsonb,
  changed_at timestamptz not null default now()
);

